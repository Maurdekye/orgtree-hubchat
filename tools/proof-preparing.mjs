// Isolated browser-mock proof; no app, device, account or hub is opened.
import { createServer } from 'vite';
import { launch } from './cdp.mjs';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
const out=resolve(process.env.HUBCHAT_PROOF_OUT || 'D:/orgtree-work/rig/agy-astra/hubchat-preparing');
mkdirSync(out,{recursive:true});
const server=await createServer({server:{host:'127.0.0.1',port:0}});await server.listen();
const url=server.resolvedUrls.local[0];
const b=await launch();const checks=[];
const check=(name,ok)=>{checks.push({name,ok});console.log(`${ok?'PASS':'FAIL'} ${name}`);if(!ok)throw Error(name);};
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
try {
 await b.nav(url);
 await b.eval(`window.row=document.querySelector('.crow'); window.row.click(); Math.random=()=>0;`);
 await sleep(300);
 await b.type('.composer textarea','preparation navigation proof');
 await b.click('[aria-label="Attach files"]');
 await b.eval(`(async()=>{const {api}=await import('/src/api.ts');window.api=api;window.sendOriginal=api.send;window.calls=0;api.send=async m=>{window.calls++;window.sentMessage=m;await new Promise(r=>window.releaseSend=r);return window.sendOriginal(m);};})()`);
 await b.click('.sendbtn',50);
 check('preparing shown before admission',await b.eval(`!!document.querySelector('.comp-preparing') && document.querySelector('.composer textarea').disabled && window.calls===1`));
 await b.eval(`document.querySelector('.sendbtn').click();`);
 check('duplicate send blocked',await b.eval(`window.calls===1`));
 await b.eval(`window.other=document.querySelectorAll('.crow')[1];window.other.click()`);await sleep(150);
 await b.type('.composer textarea','other chat draft stays');
 await b.eval(`window.row.click()`);await sleep(150);
 check('preparation restored after navigation',await b.eval(`document.querySelector('.comp-preparing')?.textContent.includes('Preparing') && document.querySelector('.composer textarea').value==='preparation navigation proof' && document.querySelectorAll('.attchip').length===1`));
 await b.eval(`window.releaseSend()`);await sleep(450);
 check('byte progress reaches UI',await b.eval(`(async()=>{const s=await import('/src/lib/store.ts');const f=await import('/src/lib/format.ts');const p=s.getPreparation(window.sentMessage.peer);return p.done>0 && p.done<p.total && document.querySelector('.comp-preparing')?.textContent.includes(f.bytes(p.done));})()`));
 await b.shot(join(out,'preparing-desktop.png'));
 await sleep(1400);
 check('admitted message clears preparation and composer',await b.eval(`!document.querySelector('.comp-preparing') && document.querySelector('.composer textarea').value===''`));
 await b.eval(`window.other.click()`);await sleep(150);
 check('other chat draft preserved',await b.eval(`document.querySelector('.composer textarea').value==='other chat draft stays'`));
 await b.eval(`window.row.click()`);await sleep(150);
 await b.type('.composer textarea','retryable preparation');await b.click('[aria-label="Attach files"]');
 await b.eval(`window.api.send=async()=>{await new Promise(r=>setTimeout(r,100));throw 'not enough space to prepare these files; free space and try again';}`);
 await b.click('.sendbtn',350);
 check('failed preparation keeps draft and attachments',await b.eval(`document.querySelector('[role="alert"]')?.textContent.includes('not enough space') && document.querySelector('.composer textarea').value==='retryable preparation' && document.querySelectorAll('.attchip').length===1 && !document.querySelector('.sendbtn').disabled`));
 await b.shot(join(out,'preparing-failed-desktop.png'));
 await b.eval(`window.api.send=window.sendOriginal`);await b.click('.sendbtn',1700);
 check('explicit retry admits message',await b.eval(`!document.querySelector('[role="alert"]') && document.querySelector('.composer textarea').value===''`));
 await b.size(390,844);await b.nav(url+'?platform=android');
 await b.eval(`if(!document.querySelector('.composer')) document.querySelector('.rrow').click();Math.random=()=>0;`);await sleep(150);
 await b.type('.composer textarea','phone preparation proof');await b.click('[aria-label="Attach files"]');
 await b.click('.sendbtn',400);
 check('mobile layout shows preparation',await b.eval(`!!document.querySelector('.comp-preparing') && document.querySelector('.composer textarea').disabled && document.documentElement.scrollWidth<=innerWidth`));
 await b.shot(join(out,'preparing-mobile.png'));await sleep(1300);
 check('mobile preparation settles',await b.eval(`!document.querySelector('.comp-preparing') && document.querySelector('.composer textarea').value===''`));
 writeFileSync(join(out,'result.json'),JSON.stringify({checks},null,2));
} finally { await b.close();await server.close(); }
