// Native launchers run without a WebView. Generate their palette from the app's
// CSS; pin the tiny formatter translation so a client edit cannot silently drift.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root = new URL('../', import.meta.url);
const read = p => fs.readFileSync(new URL(p, root), 'utf8');
export const formatter = read('src/lib/format.ts').match(/export function initials\(name: string\): string \{([\s\S]*?)\n\}/)[1].trim();
const expected = String.raw`const w = String(name || "?").replace(/[^\p{L}\p{N} ]/gu, " ").trim().split(/\s+/);
  return ((w[0] || "?")[0] + (w.length > 1 ? w[w.length - 1][0] : "")).toUpperCase();`;
assert.equal(formatter.replace(/\s+/g,' '), expected.replace(/\s+/g,' '), 'Update native initials translation and parity cases when the client formatter changes');
export const clientInitials = new Function('name', formatter);
const css = read('src/styles/tokens.css');
function color(value) {
  if (value.startsWith('#')) return '0xff' + value.slice(1) + '.toInt()';
  const rgba = value.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/);
  assert.ok(rgba, 'known CSS colour syntax');
  return '0x' + [Math.round(Number(rgba[4])*255), ...rgba.slice(1,4).map(Number)].map(n=>n.toString(16).padStart(2,'0')).join('') + '.toInt()';
}
const palettes = ['dark','light'].map(theme => {
  const block = css.match(new RegExp('\\.theme-' + theme + ' \\{([\\s\\S]*?)\\}'))[1];
  const value = name => color(block.match(new RegExp('--k-' + name + ':\\s*([^;]+)'))[1]);
  return `  private val ${theme} = arrayOf(LauncherColors(${value('person-bg')}, ${value('person')}), LauncherColors(${value('org-bg')}, ${value('org')}))\n  private val ${theme}Surface = ${color(block.match(/--bg:\s*([^;]+)/)[1])}`;
});
export const generated = `// GENERATED by tools/generate-launcher-avatar.mjs from format.ts + tokens.css.
// Do not edit: preBuild and focused verification check this against client source.
package dev.orgtree.hubchat
import java.util.Locale

internal data class LauncherColors(val background: Int, val foreground: Int)
internal object LauncherAvatarRecipe {
${palettes.join('\n')}
  fun colors(kind: String, night: Boolean): LauncherColors = (if (night) dark else light)[if (kind == "org") 1 else 0]
  fun over(foreground: Int, background: Int): Int {
    val alpha = foreground ushr 24
    var result = 0xff000000.toInt()
    for (shift in intArrayOf(16, 8, 0)) {
      val channel = (((foreground ushr shift and 255) * alpha + (background ushr shift and 255) * (255-alpha) + 127) / 255)
      result = result or (channel shl shift)
    }
    return result
  }
  fun profileBackground(kind: String, night: Boolean): Int = over(colors(kind, night).background, if (night) darkSurface else lightSurface)
  fun initialsColors(kind: String, night: Boolean): LauncherColors = LauncherColors(profileBackground(kind, night), colors(kind, night).foreground)
  fun initials(name: String): String {
    val words = name.ifEmpty { "?" }.replace(Regex("[^\\\\p{L}\\\\p{N} ]"), " ").trim().split(Regex("\\\\s+"))
    return ((words[0].firstOrNull()?.toString() ?: "?") + (if (words.size > 1) words.last().first().toString() else "")).uppercase(Locale.ROOT)
  }
}
`;
const target = new URL('src-tauri/gen/android/app/src/main/java/dev/orgtree/hubchat/LauncherAvatarRecipe.kt', root);
if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  if (process.argv.includes('--write')) fs.writeFileSync(target, generated);
  else assert.equal(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n'), generated, 'Regenerate launcher avatar recipe with --write');
  if (process.argv.includes('--fixtures')) {
    const path = process.argv[process.argv.indexOf('--fixtures') + 1];
    assert.ok(path.replaceAll('\\','/').startsWith('C:/orgtree-build/hubchat-jumplist-sol/'));
    const names = ['',' ','?','Example Person','One','three word name','123 Name','Anne-Marie O’Neil','école française','世界 朋友','ß ö','A\tB','🙂','𝒜 Tester','אורי ישראל','محمد علي','--x--','a.b.c','e\u0301 Smith'];
    const literal = s => 'charArrayOf(' + s.split('').map(c=>'0x'+c.charCodeAt(0).toString(16)+'.toChar()').join(',') + ').concatToString()';
    const checks = names.map(name => `  check(LauncherAvatarRecipe.initials(${literal(name)}) == ${literal(clientInitials(name))})`);
    fs.writeFileSync(path, 'package dev.orgtree.hubchat\nfun checkLauncherAvatarParity() {\n' + checks.join('\n') + '\n  println("PASS client/native initials parity19/19")\n}\n');
  }
}
